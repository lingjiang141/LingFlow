import { spawn } from "node:child_process";
import { mkdirSync, readFileSync } from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";
const root = path.resolve(".validation", "pet-smoke-" + Date.now());
mkdirSync(root, { recursive: true });
const env = { ...process.env, LINGFLOW_PET_SMOKE_DIR: root };
delete env.ELECTRON_RUN_AS_NODE;
const child = spawn(path.resolve("node_modules/electron/dist/electron.exe"), ["--disable-gpu", "desktop/pet-smoke.cjs"], { env, windowsHide: true, stdio: ["ignore", "pipe", "pipe"] });
let output = "";
child.stdout.on("data", bytes => { output += bytes; }); child.stderr.on("data", bytes => { output += bytes; });
const timeout = setTimeout(() => child.kill(), 90000);
const code = await new Promise((resolve, reject) => { child.on("exit", resolve); child.on("error", reject); });
clearTimeout(timeout);
assert.equal(code, 0, output);
const result = JSON.parse(readFileSync(path.join(root, "result.json"), "utf8"));
assert.deepEqual(result.errors, []);
assert.equal(result.dragged, true);
assert.equal(result.closedPageKeptPet, true);
assert.equal(result.serviceClosedOnQuit, true);
assert.equal(result.allTicketsVisibleInScrollableGroups, true);
assert.equal(result.specCycleIncludesAdditions, true);
console.log(JSON.stringify({ root, ...result }));
